def secs(d):
    if not d: return 0
    p = [int(x) for x in d.split(":")]
    s = 0
    for x in p: s = s*60 + x
    return s

def build():
    items = {}
    order = 0
    for cid, _ in COURSES:
        for (iid, title, typ, dur) in ITEMS[cid]:
            assert iid not in items, iid
            items[iid] = dict(id=iid, c=cid, t=title, ty=typ, d=dur, s=secs(dur), o=order)
            order += 1
    used = set()
    areas = []
    for (n, name, res, backup, topics) in AREAS:
        tl = []
        for (tn, tier, ids) in topics:
            for i in ids:
                assert i in items, (n, tn, i)
                used.add(i)
            tl.append(dict(name=tn, tier=tier, items=ids))
        areas.append(dict(n=n, name=name, res=res, backup=backup, topics=tl))
    unused = [i for i in items if i not in used]
    assert not unused, unused
    # each item's best tier (Must wins) and areas
    for it in items.values():
        it["tier"] = "Important"; it["areas"] = []
    for a in areas:
        for t in a["topics"]:
            for i in t["items"]:
                if t["tier"] == "Must": items[i]["tier"] = "Must"
                if a["n"] not in items[i]["areas"]: items[i]["areas"].append(a["n"])
    data = dict(version=1, courses=[dict(id=c, name=n) for c, n in COURSES],
                items=list(items.values()), areas=areas)
    return data

